typedef struct {
    const char *name;
    const char *ptx;
    uint32_t bm, bn, threads;
    acuda_kernel_t *kernel;
} cand_t;

static cand_t cands[] = {
    { "64x64", PTX_64_64, 64, 64, 256, NULL },
    { "64x128", PTX_64_128, 64, 128, 512, NULL },
    { "128x64", PTX_128_64, 128, 64, 512, NULL },
};
#define NCANDS (sizeof(cands) / sizeof(cands[0]))

int main(int argc, char **argv) {
    int launches = argc > 1 ? atoi(argv[1]) : 20;
    uint32_t M = argc > 2 ? (uint32_t)strtoul(argv[2], NULL, 0) : 2048;
    uint32_t N = argc > 3 ? (uint32_t)strtoul(argv[3], NULL, 0) : 2048;
    uint32_t K = argc > 4 ? (uint32_t)strtoul(argv[4], NULL, 0) : 2048;
    if (M % 128 || N % 128 || K % 64) {
        printf("M must be a multiple of 128, N of 128, K of 64\n");
        return 2;
    }
    acuda_context_t ctx = NULL;
    if (acuda_init(&ctx) != ACUDA_SUCCESS) {
        printf("acuda_init failed\n");
        return 1;
    }
    uint32_t sel = 0;
    acuda_device_selected(ctx, &sel);
    acuda_device_info_t info;
    memset(&info, 0, sizeof(info));
    acuda_device_get(ctx, sel, &info);
    printf("GPU: %s\n", info.name);
    char err[1024];
    for (size_t i = 0; i < NCANDS; i++) {
        if (acuda_compile_ptx(cands[i].ptx, NULL, &cands[i].kernel, err,
                              sizeof(err), NULL) != ACUDA_SUCCESS) {
            printf("compile failed for %s: %s\n", cands[i].name, err);
            return 1;
        }
    }

    size_t abytes = (size_t)M * K * 2 + 256;
    size_t bbytes = (size_t)N * K * 2 + 256;
    size_t cbytes = (size_t)M * N * 4;
    uint16_t *ha = malloc(abytes), *hb = malloc(bbytes);
    float *hc = malloc(cbytes);
    if (!ha || !hb || !hc) {
        printf("host allocation failed\n");
        return 1;
    }
    for (size_t i = 0; i < (size_t)M * K; i++)
        ha[i] = 0x3c00u; // f16 1.0
    for (size_t i = 0; i < (size_t)N * K; i++)
        hb[i] = 0x3c00u;
    memset(ha + (size_t)M * K, 0, 256);
    memset(hb + (size_t)N * K, 0, 256);
    memset(hc, 0, cbytes);

    acuda_buffer_t ba = NULL, bb = NULL, bc = NULL;
    acuda_buffer_t bufs[3];
    if (acuda_malloc_device(ctx, &ba, abytes) != ACUDA_SUCCESS ||
        acuda_malloc_device(ctx, &bb, bbytes) != ACUDA_SUCCESS ||
        acuda_malloc_device(ctx, &bc, cbytes) != ACUDA_SUCCESS ||
        acuda_memcpy_h2d(ctx, ba, ha, abytes, NULL) != ACUDA_SUCCESS ||
        acuda_memcpy_h2d(ctx, bb, hb, bbytes, NULL) != ACUDA_SUCCESS) {
        printf("device setup failed\n");
        return 1;
    }
    bufs[0] = ba; bufs[1] = bb; bufs[2] = bc;

    uint32_t push[2] = { K, N };
    const char *force = getenv("ACUDA_GEMM_TILE");
    // Ramp clocks before comparing: the first kernel measured cold used to
    // look slower by ~30%, which biased the choice.
    {
        uint32_t g0 = (M / cands[0].bm) * (N / cands[0].bn);
        for (int w = 0; w < 50; w++)
            acuda_launch_kernel(ctx, cands[0].kernel, bufs, 3, push,
                                sizeof(push), g0, cands[0].threads, NULL);
        acuda_stream_synchronize(ctx, NULL);
    }
    int best = -1;
    double best_t = 1e30;
    printf("autotune %ux%ux%u:", M, N, K);
    for (int round = 0; round < 2; round++) {
        for (size_t i = 0; i < NCANDS; i++) {
            if (force && strcmp(force, cands[i].name) != 0)
                continue;
            uint32_t grid = (M / cands[i].bm) * (N / cands[i].bn);
            double t0 = now_ms();
            for (int w = 0; w < 5; w++)
                acuda_launch_kernel(ctx, cands[i].kernel, bufs, 3, push,
                                    sizeof(push), grid, cands[i].threads,
                                    NULL);
            acuda_stream_synchronize(ctx, NULL);
            double t = (now_ms() - t0) / 5.0;
            if (round == 0)
                printf("  %s %.3f ms", cands[i].name, t);
            if (t < best_t) { best_t = t; best = (int)i; }
        }
    }
    printf("  -> %s\n", best >= 0 ? cands[best].name : "(none)");
    if (best < 0) {
        printf("no usable tile (set ACUDA_GEMM_TILE?)\n");
        return 1;
    }
    cand_t *bc_sel = &cands[best];
    acuda_kernel_t *k = bc_sel->kernel;
    uint32_t grid = (M / bc_sel->bm) * (N / bc_sel->bn);

    // Correctness check on one tile (all inputs 1.0 => C = K).
    if (acuda_launch_kernel(ctx, k, bufs, 3, push, sizeof(push), 1,
                            bc_sel->threads, NULL) != ACUDA_SUCCESS ||
        acuda_stream_synchronize(ctx, NULL) != ACUDA_SUCCESS ||
        acuda_memcpy_d2h(ctx, hc, bc, cbytes, NULL) != ACUDA_SUCCESS) {
        printf("check launch failed\n");
        return 1;
    }
    float expect = (float)K;
    for (uint32_t r = 0; r < bc_sel->bm; r++)
        for (uint32_t c = 0; c < bc_sel->bn; c++)
            if (hc[(size_t)r * N + c] != expect) {
                printf("mismatch at %u,%u: %.1f != %.1f\n", r, c,
                       hc[(size_t)r * N + c], expect);
                return 1;
            }
    printf("correctness: %ux%u tile ok (C = %.0f)\n", bc_sel->bm,
           bc_sel->bn, expect);
    memset(hc, 0, cbytes);

    for (int i = 0; i < 20; i++)
        acuda_launch_kernel(ctx, k, bufs, 3, push, sizeof(push), grid,
                            bc_sel->threads, NULL);
    acuda_stream_synchronize(ctx, NULL);

    enum { ROUNDS = 7 };
    double t[ROUNDS];
    double flops = 2.0 * (double)M * (double)N * (double)K;
    for (int r = 0; r < ROUNDS; r++) {
        double t0 = now_ms();
        for (int i = 0; i < launches; i++)
            if (acuda_launch_kernel(ctx, k, bufs, 3, push, sizeof(push),
                                    grid, bc_sel->threads, NULL) !=
                ACUDA_SUCCESS) {
                printf("launch failed\n");
                return 1;
            }
        acuda_stream_synchronize(ctx, NULL);
        t[r] = (now_ms() - t0) / (double)launches;
    }
    qsort(t, ROUNDS, sizeof(double), cmp_double);
    printf("gemm %ux%ux%u [%s]  min %8.3f ms  median %8.3f ms  %8.1f GFLOP/s\n",
           M, N, K, bc_sel->name, t[0], t[ROUNDS / 2],
           flops / t[0] / 1e6);

    acuda_free(ctx, ba);
    acuda_free(ctx, bb);
    acuda_free(ctx, bc);
    for (size_t i = 0; i < NCANDS; i++)
        acuda_kernel_free(cands[i].kernel);
    acuda_shutdown(ctx);
    free(ha);
    free(hb);
    free(hc);
    return 0;
}
